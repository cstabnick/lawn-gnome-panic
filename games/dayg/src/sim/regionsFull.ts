/** The region graph for a map: the slice graph is regions.ts's own; the full graph is built once. */
export function graphFor(map: MapKind): RegionGraph {
  if (map === 'full') {
    if (!fullGraph) fullGraph = buildFullGraph();
    return fullGraph;
  }
  return buildGraph();
}
export function regionsFor(map: MapKind): readonly RegionDef[] {
  return map === 'full' ? FULL_REGIONS : REGIONS;
}
const DISTRICT_OF: Record<string, DistrictId> = Object.fromEntries(FULL_REGIONS.map((r) => [r.id, r.district]));
export function districtOf(r: RegionId): DistrictId {
  const d = DISTRICT_OF[r];
  if (!d) throw new Error(`no district for region ${r}`);
  return d;
}
