// Compiles assembly/kernel.ts -> src/wasm/kernelBytes.ts (base64 for zero-plugin Vite/Vitest/esbuild).
// Usage: npm run build:wasm -w games/gnomes-of-gnomomia
import { main as ascMain } from 'assemblyscript/asc';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const outDir = join(root, 'src/wasm');
mkdirSync(outDir, { recursive: true });
rmSync(join(outDir, 'kernel.wasm'), { force: true });

let compiledBytes = null;
const { error, stderr } = await ascMain(
  [
    join(root, 'assembly/kernel.ts'),
    '--outFile', 'kernel.wasm',
    '--runtime', 'stub',
    '--optimizeLevel', '3',
    '--shrinkLevel', '2',
    '--converge',
    '--noAssert',
    '--enable', 'simd',
    '--initialMemory', '416',
    '--maximumMemory', '416',
    '--stackSize', '32768',
  ],
  {
    writeFile(filename, contents) {
      if (filename.endsWith('kernel.wasm')) {
        compiledBytes = Buffer.from(contents);
      }
    },
  },
);

if (error || !compiledBytes) {
  console.error(stderr.toString());
  process.exit(1);
}

const b64 = compiledBytes.toString('base64');
const ts = `// Generated by scripts/build-wasm.mjs from assembly/kernel.ts — do not edit by hand.\nexport const KERNEL_WASM_BASE64 = '${b64}';\n`;
writeFileSync(join(outDir, 'kernelBytes.ts'), ts);
console.log(`built kernel.wasm (${compiledBytes.length} bytes) -> src/wasm/kernelBytes.ts`);
