/**
 * A shuffled order of indexes into PROMPTS, for Room.promptOrder. Fisher-Yates: every permutation is equally likely
 * (given a fair `rand`). `rand` returns values in [0, 1); the clamp keeps an out-of-range value from breaking the index.
 */
export function shufflePromptOrder(rand: () => number = Math.random): number[] {
  const order = PROMPTS.map((_, i) => i);
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.min(i, Math.floor(rand() * (i + 1)));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
}
